#!/usr/bin/env bun
// OpenAPI contract check (P0.4).
//
//   (a) Lints api/openapi.yaml with @redocly/cli — zero errors required;
//       warnings are allowed only when they match ALLOWED_WARNINGS.
//   (b) Boots `wrangler dev --local` for api/spike on a fixed port, POSTs
//       every fixtures/*.jpg through /v1-verify (public VerifyResult shape)
//       and validates each response against the spec's VerifyResult schema
//       with ajv (2020-12). Two fixtures also run with the full include set
//       to exercise thumbnails/raw_manifest/gps branches.
//   (c) Validates fixtures/golden/*.c2paMini.json against MiniResult.
//   (d) Validates every example embedded in the spec against its schema.
//
// The wrangler dev process is killed on every exit path.

import { spawn, spawnSync } from 'node:child_process';
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = join(ROOT, 'api/openapi.yaml');
const SPIKE = join(ROOT, 'api/spike');
const FIXTURES = join(ROOT, 'fixtures');
const GOLDEN = join(FIXTURES, 'golden');
const PORT = 8798;
const BASE = `http://localhost:${PORT}`;
const LINT_CMD = ['bunx', '@redocly/cli@2.83.0', 'lint', 'api/openapi.yaml'];

// Warnings we accept from redocly, matched as substrings of the
// "Warning was generated by the <rule> rule." line.
const ALLOWED_WARNINGS = [
  // /openapi.json serves the spec document itself; a 4xx response is not
  // meaningful for it (the document either exists or the route is absent).
  'operation-4xx-response',
];

let failures = 0;
const fail = (msg) => { failures++; console.log(`FAIL  ${msg}`); };
const ok = (msg) => console.log(`ok    ${msg}`);

// ---------------------------------------------------------------- lint ----

function lintSpec() {
  console.log('\n== redocly lint ==');
  const res = spawnSync(LINT_CMD[0], LINT_CMD.slice(1), { cwd: ROOT, encoding: 'utf8' });
  const out = `${res.stdout || ''}${res.stderr || ''}`;
  process.stdout.write(out);
  const errors = (out.match(/Error was generated by the/g) || []).length;
  const warnings = [...out.matchAll(/Warning was generated by the ([\w-]+) rule/g)].map((m) => m[1]);
  const badWarnings = warnings.filter((w) => !ALLOWED_WARNINGS.includes(w));
  if (errors > 0) fail(`lint: ${errors} error(s)`);
  else if (badWarnings.length) fail(`lint: disallowed warning(s): ${badWarnings.join(', ')}`);
  else ok(`lint clean (${warnings.length} allowed warning(s): ${warnings.join(', ') || 'none'})`);
}

// ------------------------------------------------------------- ajv setup --

const doc = parseYaml(readFileSync(SPEC, 'utf8'));
const ajv = new Ajv2020({ strict: false, allErrors: true });
addFormats(ajv);
// Register the components subtree so '#/components/schemas/X' refs resolve.
ajv.addSchema({ components: { schemas: doc.components.schemas } }, 'spec');

function schemaValidator(schema, trail) {
  if (!schema || typeof schema !== 'object') return null;
  if (schema.$ref) {
    const m = schema.$ref.match(/^#\/components\/schemas\/(\w+)$/);
    if (m) return ajv.getSchema(`spec#/components/schemas/${m[1]}`) || null;
    return null; // external/other refs — not used for examples
  }
  if (Array.isArray(schema.allOf)) {
    // e.g. Problem + extra members: validate against the components ref
    // branch (Problem allows additional properties).
    for (const sub of schema.allOf) {
      const v = schemaValidator(sub, trail);
      if (v) return v;
    }
    return null;
  }
  try {
    return ajv.compile(schema);
  } catch (e) {
    console.log(`  (skip inline schema at ${trail}: ${e.message})`);
    return null;
  }
}

// ------------------------------------------------------- example walker ----

// Collect {validator, values:[{trail, value}]} for every media-type or
// parameter object carrying example/examples next to a schema.
function collectExamples(node, trail, out = []) {
  if (!node || typeof node !== 'object') return out;
  const hasSchema = !!node.schema;
  if (hasSchema && node.examples && typeof node.examples === 'object') {
    const vals = [];
    for (const [k, ex] of Object.entries(node.examples)) {
      const v = ex && typeof ex === 'object' && 'value' in ex ? ex.value : ex;
      vals.push({ trail: `${trail}/examples/${k}`, value: v });
    }
    const v = schemaValidator(node.schema, trail);
    if (v) out.push({ validator: v, vals, trail });
  }
  if (hasSchema && node.example !== undefined) {
    const v = schemaValidator(node.schema, trail);
    if (v) out.push({ validator: v, vals: [{ trail: `${trail}/example`, value: node.example }], trail });
  }
  for (const [k, child] of Object.entries(node)) {
    if (k === 'examples' || k === 'example' || k === 'schema') continue;
    collectExamples(child, `${trail}/${k}`, out);
  }
  return out;
}

function validateExamples() {
  console.log('\n== spec examples ==');
  const groups = collectExamples(doc, '');
  let checked = 0;
  for (const g of groups) {
    for (const { trail, value } of g.vals) {
      checked++;
      if (g.validator(value)) ok(`example ${trail}`);
      else fail(`example ${trail}: ${JSON.stringify(g.validator.errors).slice(0, 400)}`);
    }
  }
  if (!checked) fail('no examples found in spec');
  else console.log(`     (${checked} example values checked)`);
}

// ------------------------------------------------------------- wrangler ----

async function portFree(port) {
  try {
    const r = await fetch(`http://localhost:${port}/health`, { signal: AbortSignal.timeout(800) });
    return false; // something answered — not free (or our own server)
  } catch {
    return true;
  }
}

async function waitHealth(child, timeoutMs = 60000) {
  const t0 = Date.now();
  while (Date.now() - t0 < timeoutMs) {
    if (child.exitCode !== null) throw new Error(`wrangler exited early (code ${child.exitCode})`);
    try {
      const r = await fetch(`${BASE}/health`, { signal: AbortSignal.timeout(1000) });
      if (r.ok) return;
    } catch { }
    await new Promise((r) => setTimeout(r, 400));
  }
  throw new Error('wrangler dev did not become healthy in time');
}

function stopChild(child) {
  return new Promise((resolvePromise) => {
    if (!child || child.exitCode !== null || child.killed) return resolvePromise();
    const t = setTimeout(() => { try { child.kill('SIGKILL'); } catch { } resolvePromise(); }, 8000);
    child.once('exit', () => { clearTimeout(t); resolvePromise(); });
    try { child.kill('SIGTERM'); } catch { resolvePromise(); }
  });
}

// ------------------------------------------------------------- corpus ------

async function postVerify(file, query = '') {
  const bytes = readFileSync(join(FIXTURES, file));
  const resp = await fetch(`${BASE}/v1-verify${query}`, {
    method: 'POST',
    headers: { 'x-mime': 'image/jpeg', 'x-filename': file },
    body: bytes,
  });
  const text = await resp.text();
  let json = null;
  try { json = JSON.parse(text); } catch { }
  return { status: resp.status, json, text };
}

const validateVerifyResult = ajv.getSchema('spec#/components/schemas/VerifyResult');
const validateMini = ajv.getSchema('spec#/components/schemas/MiniResult');

async function runCorpus() {
  console.log('\n== /v1-verify corpus ==');
  const fixtures = readdirSync(FIXTURES).filter((f) => f.toLowerCase().endsWith('.jpg')).sort();
  for (const f of fixtures) {
    const { status, json } = await postVerify(f);
    if (status !== 200) { fail(`${f}: HTTP ${status} ${JSON.stringify(json).slice(0, 200)}`); continue; }
    if (validateVerifyResult(json)) {
      ok(`${f} (status=${json.status}, trust=${json.trust && json.trust.basis})`);
    } else {
      fail(`${f}: schema — ${JSON.stringify(validateVerifyResult.errors).slice(0, 500)}`);
    }
  }

  // Full include set on two fixtures to exercise optional sections.
  console.log('\n== /v1-verify full include ==');
  for (const f of ['C.jpg', 'DSCF9243.jpg']) {
    const q = '?include=exif,iptc,gps,thumbnails,raw_manifest&strip_gps=false';
    const { status, json } = await postVerify(f, q);
    if (status !== 200) { fail(`${f} full-include: HTTP ${status}`); continue; }
    const hasThumbs = json.thumbnails && Object.keys(json.thumbnails).length > 0;
    const hasRaw = 'raw_manifest' in json;
    if (validateVerifyResult(json)) {
      ok(`${f} full-include (thumbnails=${hasThumbs}, raw_manifest=${hasRaw}, gps=${JSON.stringify(json.metadata.gps)})`);
    } else {
      fail(`${f} full-include: schema — ${JSON.stringify(validateVerifyResult.errors).slice(0, 500)}`);
    }
  }

  // strip_gps=true must null gps even when requested.
  {
    const { json } = await postVerify('DSCF9243.jpg', '?include=gps&strip_gps=true');
    if (json && json.metadata && json.metadata.gps === null && validateVerifyResult(json)) {
      ok('DSCF9243.jpg strip_gps=true -> metadata.gps null');
    } else {
      fail(`strip_gps check: ${JSON.stringify(json && json.metadata).slice(0, 200)}`);
    }
  }
}

async function runMiniGoldens() {
  console.log('\n== mini goldens ==');
  const files = readdirSync(GOLDEN).filter((f) => f.endsWith('.c2paMini.json'));
  for (const f of files.sort()) {
    const value = JSON.parse(readFileSync(join(GOLDEN, f), 'utf8'));
    if (validateMini(value)) ok(f);
    else fail(`${f}: ${JSON.stringify(validateMini.errors).slice(0, 400)}`);
  }
}

// ------------------------------------------------------------------ main --

async function main() {
  lintSpec();
  validateExamples();
  runMiniGoldens();

  if (!(await portFree(PORT))) {
    fail(`port ${PORT} is not free — refusing to start wrangler`);
    return;
  }

  const child = spawn('bunx', ['wrangler', 'dev', '--local', '--port', String(PORT)], {
    cwd: SPIKE,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  let wranglerLog = '';
  child.stdout.on('data', (d) => { wranglerLog += d; });
  child.stderr.on('data', (d) => { wranglerLog += d; });

  const onSignal = async () => { await stopChild(child); process.exit(130); };
  process.on('SIGINT', onSignal);
  process.on('SIGTERM', onSignal);

  try {
    await waitHealth(child);
    await runCorpus();
  } catch (e) {
    fail(`worker harness: ${e.message}`);
    if (wranglerLog) console.log('--- wrangler output (tail) ---\n' + wranglerLog.split('\n').slice(-25).join('\n'));
  } finally {
    await stopChild(child);
    // give workerd a moment to die, then verify nothing is left
    await new Promise((r) => setTimeout(r, 500));
  }

  console.log(failures ? `\n${failures} openapi-check failure(s)` : '\nopenapi-check: all good');
  process.exit(failures ? 1 : 0);
}

main().catch((e) => { console.error(e); process.exit(1); });
